function getLang() {
  const stored = localStorage.getItem(LANG_KEY);
  return stored === 'ru' || stored === 'en' ? stored : 'en';
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang;
  renderLangSwitcher();
  if (typeof window.onLangChange === 'function') window.onLangChange();
}

// {placeholder} substitution. If vars.count is present, picks the
// `${key}_plural` variant when count !== 1 (English-style pluralization —
// Russian's real plural rules are more complex, but this dashboard's counts
// are all small/approximate enough that the simple singular/plural split
// reads fine and matches what's used for `count`/`total`).
function t(key, vars) {
  const lang = getLang();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let k = key;
  if (vars && typeof vars.count === 'number' && vars.count !== 1 && dict[`${key}_plural`]) {
    k = `${key}_plural`;
  }
  let str = dict[k] ?? TRANSLATIONS.en[k] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      str = str.replaceAll(`{${name}}`, value);
    }
  }
  return str;
}

// Renders/updates the EN/RU switcher into any element with id="lang-switch"
// present in the page's header. Safe to call before that element exists
// (e.g. nothing to do yet) — pages call it once on load and again from
// setLang().
function renderLangSwitcher() {
  const el = document.getElementById('lang-switch');
  if (!el) return;
  const lang = getLang();
  el.innerHTML = `
    <button class="lang-btn ${lang === 'en' ? 'active' : ''}" onclick="setLang('en')">EN</button>
    <button class="lang-btn ${lang === 'ru' ? 'active' : ''}" onclick="setLang('ru')">RU</button>
  `;
}

